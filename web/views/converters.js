export function isJalbumPage(htmlContent) {
    const html = String(htmlContent || '');
    if (/Generated by jAlbum/i.test(html)) return true;
    if (/<meta\b[^>]*\bname\s*=\s*["']generator["'][^>]*jAlbum/i.test(html)) return true;
    if (/<meta\b[^>]*\bcontent\s*=\s*["'][^"']*jAlbum[^"']*["'][^>]*\bname\s*=\s*["']generator["']/i.test(html)) return true;
    if (/_jaSkin\s*=/.test(html)) return true;
    if (/jalbum\.net\/widgetapi/i.test(html)) return true;
    if (/id\s*=\s*["']jalbumwidgetcontainer["']/i.test(html)) return true;
    return false;
}

export function analyzeJalbumPage(htmlContent, pageData, galleryData) {
    const html = String(htmlContent || '');
    const page = pageData && typeof pageData === 'object' ? pageData : {};
    const warnings = [];
    const notes = [];
    const isJalbum = isJalbumPage(html);
    const path = pagePathOf(page, html);
    const parsed = parseJalbumImages(html);
    const photos = mergePhotos(parsed.images, galleryImages(galleryData));
    const heading = heroCopy(html);
    const titleTag = plainText(matchTag(html, 'title'));
    const metaDescription = metaContent(html, 'description');
    const pageValues = readPageValues(html, {
        title: titleTag || heading.h1,
        description: metaDescription || heading.description || titleTag || heading.h1,
        image: shareImage(html, path, photos),
    }, warnings);
    const related = readRelatedSales(html, warnings);
    const pidInfo = readPid(html, page.section, warnings);
    const back = backLink(html);
    const siblings = siblingLinks(page);
    const skin = skinInfo(html, parsed.markup);
    if (parsed.slidePages) warnings.push(`Found ${parsed.slidePages} legacy slides/*.html link${parsed.slidePages === 1 ? '' : 's'}. Those HTML slide pages are not copied as images.`);
    if (isJalbum && !photos.length) warnings.push('No gallery photos were found in the page or gallery data.');
    if (isJalbum && photos.length && photos.every((photo) => !photo.caption)) {
        notes.push('None of the photos have a caption. Lightbox titles use the decoded file names.');
    }
    if (isJalbum && photos.length > parsed.images.length) {
        const extra = photos.length - parsed.images.length;
        notes.push(`${extra} photo${extra === 1 ? '' : 's'} past the first jAlbum batch ${extra === 1 ? 'was' : 'were'} read from gallery data so the full album is kept.`);
    }
    if (isJalbum && siblings.length) {
        notes.push('A written page sits beside this gallery. It stays on disk. The converted page can link to it.');
    }
    if (isJalbum) notes.push('jAlbum skin files stay in the folder. The new page drops res/, album.rss, folderimg, and the jAlbum widget.');
    if (!isJalbum) {
        warnings.length = 0;
        notes.length = 0;
        warnings.push('This page is not a jAlbum gallery. The converter leaves the editor unchanged.');
    }
    return {
        isJalbum,
        path,
        section: page.section || sectionFromPath(path),
        slug: page.slug || '',
        skin,
        title: pageValues.title,
        albumTitle: heading.h1 || pageValues.title,
        description: pageValues.description,
        subtitle: heading.description,
        shareImage: pageValues.image,
        pageValues,
        relatedSales: related,
        pid: pidInfo.pid,
        pidPreserved: pidInfo.preserved,
        login: pidInfo.login,
        measurementId: readMeasurementId(html),
        photos,
        photoCount: photos.length,
        captionCount: photos.filter((photo) => photo.caption).length,
        backLink: back,
        siblings,
        lightboxId: lightboxId(page, path, heading.h1 || pageValues.title),
        canonicalUrl: path ? publicUrl(path) : '',
        warnings,
        notes,
    };
}

export function convertJalbumToModern(htmlContent, pageData, galleryData, options) {
    const analysis = analyzeJalbumPage(htmlContent, pageData, galleryData);
    if (!analysis.isJalbum) return String(htmlContent || '');
    return renderModernPage(analysis, options || {});
}

export function mountJalbumConverter({ context, onApply } = {}) {
    if (typeof document === 'undefined') return { open() {}, close() {} };
    const dialog = el('dialog', { class: 'converter-dialog', 'aria-labelledby': 'jalbum-converter-title' });
    const head = el('div', { class: 'dialog-head' });
    head.append(el('h2', { id: 'jalbum-converter-title', text: 'jAlbum → Modern Lightbox' }));
    const close = el('button', { class: 'btn', text: 'Close', title: 'Close the jAlbum converter' });
    close.addEventListener('click', () => dialog.close());
    head.append(close);
    const body = el('div', { class: 'dialog-body' });
    dialog.append(head, body);
    document.body.append(dialog);

    async function open() {
        const ctx = typeof context === 'function' ? (context() || {}) : {};
        let galleryData = ctx.galleryData || {};
        body.replaceChildren(el('p', { class: 'field-hint', text: 'Reading the jAlbum album…' }));
        if (!dialog.open) dialog.showModal();
        if (typeof ctx.loadGallery === 'function') {
            try {
                const loaded = await ctx.loadGallery();
                if (loaded && (Array.isArray(loaded.objects) || Array.isArray(loaded.images))) galleryData = loaded;
            } catch { /* the editor's image list is the fallback */ }
        }
        if (!dialog.open) return;
        const analysis = analyzeJalbumPage(ctx.html || '', ctx.pageData || {}, galleryData);
        renderInspector(body, analysis, ctx, () => {
            const html = convertJalbumToModern(ctx.html || '', ctx.pageData || {}, galleryData, readOptions(body));
            dialog.close();
            if (html !== String(ctx.html || '')) onApply?.(html);
        });
        body.querySelector('[data-apply]')?.focus();
    }

    return { open, close() { dialog.close(); } };
}

function renderInspector(body, analysis, ctx, apply) {
    body.replaceChildren();
    body.append(el('p', {
        class: 'field-hint',
        text: 'This writes the converted page into the open editor and refreshes the preview. The file on disk stays as it is until you click Save.',
    }));
    if (!ctx.html) {
        body.append(el('p', { text: 'Open a jAlbum page first.' }));
        return;
    }
    const rows = [
        ['File', analysis.path || 'Open editor'],
        ['Skin', skinLabel(analysis)],
        ['Title', analysis.title || '—'],
        ['Album heading', analysis.albumTitle || '—'],
        ['Description', analysis.description || '—'],
        ['Subtitle', analysis.subtitle || '—'],
        ['Share image', analysis.shareImage || '—'],
        ['Page values', analysis.pageValues.present ? 'Preserved' : 'Synthesized from the title, description, and share image'],
        ['Related sales', relatedLabel(analysis.relatedSales)],
        ['eXTReMe pid', `${analysis.pid || '—'}${analysis.pidPreserved ? ' (preserved)' : ' (section default)'}`],
        ['Photos', `${analysis.photoCount} photo${analysis.photoCount === 1 ? '' : 's'}, ${analysis.captionCount} with captions`],
        ['Canonical', analysis.canonicalUrl || '—'],
        ['Back link', analysis.backLink ? `${analysis.backLink.label} → ${analysis.backLink.href}` : '—'],
        ['Written page', analysis.siblings.length ? analysis.siblings.map((item) => item.href).join(', ') : '—'],
    ];
    if (analysis.photos[0]) {
        const first = analysis.photos[0];
        rows.push(['First photo', `${first.slide}${first.caption ? ` — ${first.caption}` : ''}`]);
    }
    body.append(definitionList(rows));
    if (analysis.photos.length > 1) {
        const samples = el('ul', { class: 'converter-samples' });
        for (const photo of analysis.photos.slice(0, 6)) {
            samples.append(el('li', { text: photo.caption || photo.label || photo.name }));
        }
        if (analysis.photos.length > 6) samples.append(el('li', { text: `and ${analysis.photos.length - 6} more` }));
        body.append(samples);
    }
    const options = el('div', { class: 'converter-options' });
    options.append(checkOption('promote-first', 'Promote photo #1 to top Feature Figure', analysis.photos.length > 0, true));
    if (analysis.siblings.length) {
        options.append(checkOption('link-siblings', 'Link the written article in this folder', true, true));
    }
    body.append(options);
    const plan = el('p', { class: 'field-hint', 'data-plan': 'true' });
    const refreshPlan = () => {
        plan.textContent = planText(analysis, readOptions(body));
    };
    options.addEventListener('change', refreshPlan);
    refreshPlan();
    body.append(plan);
    for (const note of analysis.notes) body.append(el('p', { class: 'field-hint', text: note }));
    if (analysis.warnings.length) {
        const list = el('ul', { class: 'converter-notes' });
        for (const warning of analysis.warnings) list.append(el('li', { text: warning }));
        body.append(list);
    }
    const actions = el('div', { class: 'converter-actions' });
    const button = el('button', {
        class: 'btn btn-primary',
        'data-apply': 'true',
        text: 'Apply to Editor Buffer (Unsaved Preview)',
        title: 'Replace the open editor buffer and refresh the preview. Does not save the file.',
        disabled: !analysis.isJalbum,
    });
    button.addEventListener('click', apply);
    actions.append(button);
    body.append(actions);
}

function checkOption(name, label, enabled, checked) {
    const row = el('label');
    const input = el('input', { type: 'checkbox', 'data-option': name, disabled: !enabled });
    input.checked = Boolean(checked && enabled);
    row.append(input, document.createTextNode(` ${label}`));
    return row;
}

function readOptions(body) {
    const checked = (name) => Boolean(body.querySelector(`[data-option="${name}"]`)?.checked);
    return {
        promoteFirst: checked('promote-first'),
        linkSiblings: checked('link-siblings') || !body.querySelector('[data-option="link-siblings"]'),
    };
}

function planText(analysis, options) {
    if (!analysis.isJalbum) return 'Nothing will be applied.';
    const feature = options.promoteFirst && analysis.photos.length
        ? 'Photo 1 becomes the feature figure. '
        : 'Photos stay in the gallery. ';
    const rest = options.promoteFirst ? Math.max(0, analysis.photos.length - 1) : analysis.photos.length;
    const gallery = rest
        ? `${rest} photo${rest === 1 ? '' : 's'} go in the Lightbox gallery.`
        : 'The gallery section is omitted because every photo is in the feature figure.';
    return `${feature}${gallery}`;
}

function definitionList(rows) {
    const list = el('dl', { class: 'about-dl' });
    for (const [label, value] of rows) {
        list.append(el('dt', { text: label }), el('dd', { text: value || '—' }));
    }
    return list;
}

function skinLabel(analysis) {
    const skin = analysis.skin || {};
    return [skin.generator || skin.name || 'jAlbum', skin.markup].filter(Boolean).join(' · ');
}

function relatedLabel(related) {
    if (!related?.present) return 'Empty template';
    const parts = [related.vehicleType, related.makeType, related.vehicleName].filter(Boolean);
    if (related.overrideIds) parts.push(`Override IDs ${related.overrideIds}`);
    return parts.join(' · ') || 'Preserved';
}

