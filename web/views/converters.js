function renderTracker(login, pid) {
    const safeLogin = /^[A-Za-z0-9_-]+$/.test(login) ? login : extremeLogin();
    const safePid = /^[A-Za-z0-9_-]+$/.test(pid) ? pid : 'articles';
    const host = extremeHost();
    return [
        '<!-- Start eXTReMe Pro Tracker Code -->',
        '<script>',
        'EXd = document;',
        'location.protocol == "https:" ? EXp = "https" : EXp = "http";',
        `EXd.write('<img src="' + EXp + '://${host}/n2.g?login=${safeLogin}&d=' + screen.width + 'x' + screen.height + '&auto=y&pid=${safePid}&jv=' + navigator.javaEnabled() + '&c=' + screen.colorDepth + '&l=' + escape(EXd.referrer) + '" width="0" height="0" alt="">');`,
        '</script>',
        `<noscript><img height="1" width="1" alt="" src="https://${host}/n2.g?login=${safeLogin}&amp;auto=y&amp;pid=${safePid}"></noscript>`,
        '<!-- End eXTReMe Pro Tracker Code -->',
    ].join('\n');
}

function renderGeneratedSeo(values, analysis) {
    const title = shareTitle(values.title);
    const description = escapeHtml(values.description);
    const titleAttr = escapeHtml(title);
    const url = analysis.canonicalUrl;
    const urlAttr = escapeHtml(url);
    const image = values.image && url ? assetUrl(analysis.path, values.image) : '';
    const lines = [
        '  <!-- generated-seo -->',
        '  <!-- automatically updated by render page values scripts -->',
        `  <title>${titleAttr}</title>`,
        `  <meta name="description" content="${description}">`,
        `  <link rel="canonical" href="${urlAttr}" />`,
        '  <!-- Open Graph and Twitter share card -->',
        '  <meta property="og:type" content="website">',
        `  <meta property="og:title" content="${titleAttr}">`,
        `  <meta property="og:description" content="${description}">`,
        `  <meta property="og:url" content="${urlAttr}">`,
    ];
    let card = 'summary';
    if (image) {
        lines.push(`  <meta property="og:image" content="${escapeHtml(image)}">`);
        card = 'summary_large_image';
    }
    lines.push(`  <meta name="twitter:card" content="${card}">`);
    lines.push(`  <meta name="twitter:title" content="${titleAttr}">`);
    lines.push(`  <meta name="twitter:description" content="${description}">`);
    if (image) lines.push(`  <meta name="twitter:image" content="${escapeHtml(image)}">`);
    lines.push('  <!-- Schema.org structured data -->');
    lines.push('  <script type="application/ld+json">');
    lines.push(schemaBlock(values, title, url, image));
    lines.push('  </script>');
    lines.push('  <!-- /generated-seo -->');
    return lines.join('\n');
}

function schemaBlock(values, title, url, image) {
    const schemaType = ALLOWED_TYPES.has(values.type) ? values.type : 'Article';
    const data = {
        '@context': 'https://schema.org',
        '@type': schemaType,
    };
    if (schemaType === 'CollectionPage') data.name = title;
    else data.headline = title;
    data.description = values.description;
    data.url = url;
    if (image) data.image = image;
    if (values.date) data.datePublished = values.date;
    if (schemaType === 'CollectionPage') {
        data.isPartOf = { '@type': 'WebSite', name: BRAND, url: ORIGIN };
    }
    data.publisher = { '@type': 'Organization', name: BRAND, url: ORIGIN };
    const encoded = JSON.stringify(data, null, 2).replace(/</g, '\\u003c');
    return encoded.split('\n').map((line) => `  ${line}`).join('\n');
}

function readPageValues(html, fallback, warnings) {
    const blocks = commentInners(html, 'page-values');
    if (blocks.length > 1) warnings.push('Found more than one page-values block. The first one is kept.');
    if (blocks.length) {
        const fields = parseFields(blocks[0]);
        const type = fieldValue(fields, 'type') || 'Article';
        const date = fieldValue(fields, 'date');
        if (date && !/^\d{4}-\d{2}-\d{2}$/.test(date)) warnings.push('page-values date is not YYYY-MM-DD. It stays in the comment and is left out of the schema.');
        return {
            present: true,
            synthesized: false,
            fields,
            title: stripShy(fieldValue(fields, 'title') || fallback.title),
            description: stripShy(fieldValue(fields, 'description') || fallback.description),
            image: fieldValue(fields, 'image') || fallback.image,
            type: ALLOWED_TYPES.has(type) ? type : 'Article',
            date: /^\d{4}-\d{2}-\d{2}$/.test(date) ? date : '',
        };
    }
    const title = stripShy(fallback.title || 'Untitled');
    const description = stripShy(fallback.description || title);
    const fields = [
        { key: 'title', value: title },
        { key: 'description', value: description },
    ];
    if (fallback.image) fields.push({ key: 'image', value: fallback.image });
    fields.push({ key: 'type', value: 'Article' });
    warnings.push('This page has no page-values block. One is synthesized with type Article.');
    if (!fallback.description) warnings.push('No meta description was found. The synthesized description uses the page title.');
    return {
        present: false,
        synthesized: true,
        fields,
        title,
        description,
        image: fallback.image || '',
        type: 'Article',
        date: '',
    };
}

