function backLabel(title, href) {
    const named = collapse(title);
    if (named) {
        const lower = named.toLowerCase();
        if (['awards', 'articles', 'projects'].includes(lower)) {
            return `Back to ${named.charAt(0).toUpperCase()}${named.slice(1).toLowerCase()}`;
        }
        return named;
    }
    const section = String(href || '').match(/\/(articles|awards|projects)(?:\/|$)/i);
    if (section) return `Back to ${section[1].charAt(0).toUpperCase()}${section[1].slice(1).toLowerCase()}`;
    return 'Back';
}

function siblingLinks(page) {
    const list = Array.isArray(page?.siblings) ? page.siblings : [];
    const current = String(page?.path || '').split('/').pop();
    const links = [];
    const seen = new Set();
    for (const item of list) {
        const name = typeof item === 'string' ? item.split('/').pop() : (item?.name || String(item?.path || '').split('/').pop());
        if (!name || !/\.(html|shtml|htm)$/i.test(name)) continue;
        if (/^index\.html?$/i.test(name) || name === current || seen.has(name)) continue;
        seen.add(name);
        links.push({ name, href: name, path: typeof item === 'string' ? item : (item?.path || name) });
    }
    return links;
}

