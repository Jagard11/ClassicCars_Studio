function parseJalbumImages(html) {
    const cards = parseCards(html);
    if (cards.length) return { images: cards, markup: 'Tiger cards', slidePages: countSlidePages(html) };
    const thumbs = parseAnchors(html, true);
    if (thumbs.length) return { images: thumbs, markup: 'Thumb links', slidePages: countSlidePages(html) };
    const loose = parseAnchors(html, false);
    const slidePages = countSlidePages(html);
    let markup = 'Slide links';
    if (!loose.length && slidePages) markup = 'Legacy slide pages';
    else if (/<table\b/i.test(html)) markup = 'Legacy table';
    return { images: loose, markup, slidePages };
}

function parseCards(html) {
    const source = String(html || '');
    const re = /<div\b[^>]*>/gi;
    const images = [];
    let match;
    while ((match = re.exec(source))) {
        if (insideStyleOrScript(source, match.index)) continue;
        if (!classTokens(match[0]).includes('card')) continue;
        const closeAt = closingDiv(source, match.index);
        if (closeAt < 0) continue;
        const endTag = source.indexOf('>', closeAt);
        const endPos = endTag >= 0 ? endTag + 1 : closeAt;
        const node = source.slice(match.index, endPos);
        const anchor = firstTag(node, 'a');
        if (!classTokens(anchor).includes('thumb')) {
            re.lastIndex = endPos;
            continue;
        }
        const href = attrValue(anchor, 'href');
        const imageTag = firstTag(node, 'img');
        const thumbSrc = attrValue(imageTag, 'src');
        if (!usesSlide(href) && !usesSlide(thumbSrc)) {
            re.lastIndex = endPos;
            continue;
        }
        const comment = node.match(/<div\b[^>]*\bclass\s*=\s*(?:"[^"]*\bcomment\b[^"]*"|'[^']*\bcomment\b[^']*')[^>]*>([\s\S]*?)<\/div>/i);
        images.push(rawPhoto(href, thumbSrc, comment ? plainText(comment[1]) : '', attrValue(imageTag, 'alt')));
        re.lastIndex = endPos;
    }
    return images;
}

function parseAnchors(html, thumbsOnly) {
    const source = String(html || '');
    const re = /<a\b[^>]*>/gi;
    const images = [];
    const seen = new Set();
    let match;
    while ((match = re.exec(source))) {
        if (insideStyleOrScript(source, match.index)) continue;
        const tag = match[0];
        if (thumbsOnly && !classTokens(tag).includes('thumb')) continue;
        const href = attrValue(tag, 'href');
        if (!usesSlide(href) || /\.html?$/i.test(href.split('?')[0])) continue;
        const key = fileKey(href);
        if (!key || seen.has(key)) continue;
        seen.add(key);
        const region = source.slice(match.index, match.index + 800);
        const imageTag = firstTag(region, 'img');
        images.push(rawPhoto(href, attrValue(imageTag, 'src'), '', attrValue(imageTag, 'alt')));
    }
    return images;
}

function rawPhoto(href, thumbSrc, comment, alt) {
    const name = fileBase(href || thumbSrc);
    const caption = realCaption(comment, alt, name);
    return {
        slide: href,
        thumb: thumbSrc,
        name,
        caption,
    };
}

function mergePhotos(htmlImages, dataImages) {
    const htmlList = [];
    const htmlByKey = new Map();
    for (const item of htmlImages) {
        const photo = normalizePhoto(item);
        const key = fileKey(photo.name || photo.slide);
        if (!photo.slide || !key || htmlByKey.has(key)) continue;
        htmlList.push(photo);
        htmlByKey.set(key, photo);
    }
    const dataList = [];
    const dataKeys = new Set();
    for (const item of dataImages) {
        const photo = normalizePhoto(fromGalleryItem(item));
        const key = fileKey(photo.name || photo.slide);
        if (!photo.slide || !key || dataKeys.has(key)) continue;
        dataList.push(photo);
        dataKeys.add(key);
    }
    const photos = [];
    const seen = new Set();
    for (const photo of (dataList.length ? dataList : htmlList)) {
        const key = fileKey(photo.name || photo.slide);
        const htmlPhoto = htmlByKey.get(key);
        const caption = realCaption(htmlPhoto?.caption || '', photo.caption, htmlPhoto?.name || photo.name);
        photos.push(finishPhoto({
            ...photo,
            slide: htmlPhoto?.slide || photo.slide,
            thumb: htmlPhoto?.thumb || photo.thumb || thumbFromSlide(htmlPhoto?.slide || photo.slide),
            name: htmlPhoto?.name || photo.name,
        }, caption));
        seen.add(key);
    }
    for (const photo of htmlList) {
        const key = fileKey(photo.name || photo.slide);
        if (seen.has(key)) continue;
        photos.push(finishPhoto(photo, realCaption(photo.caption, '', photo.name)));
        seen.add(key);
    }
    return photos;
}

function finishPhoto(photo, caption) {
    const text = caption || '';
    return {
        ...photo,
        caption: text,
        label: text || stemLabel(photo.name),
    };
}

function fromGalleryItem(item) {
    const href = item.href || item.image?.path || item.slideUrl || (item.path ? `slides/${String(item.path).replace(/^slides\//i, '')}` : '');
    const thumb = item.thumbSrc || item.thumb?.path || item.thumbUrl || '';
    const name = item.name || fileBase(href || thumb);
    let caption = item.caption || item.comment || '';
    if (/<[a-z!/]/i.test(caption)) caption = plainText(caption);
    else caption = collapse(decodeEntities(caption));
    return { slide: href, thumb, name, caption };
}

function normalizePhoto(photo) {
    const name = fileBase(photo?.name || photo?.slide || photo?.thumb);
    const slide = toSlide(photo?.slide, photo?.thumb, name);
    const thumb = toThumb(photo?.thumb, slide);
    return {
        slide,
        thumb,
        name: name || fileBase(slide),
        caption: collapse(photo?.caption || ''),
    };
}

function toSlide(slide, thumb, name) {
    const candidate = usesSlide(slide) && !/^thumbs\//i.test(cleanPath(slide))
        ? slide
        : (usesSlide(thumb) && /^thumbs\//i.test(cleanPath(thumb)) ? `slides/${cleanPath(thumb).replace(/^thumbs\//i, '')}` : (slide || name));
    let path = cleanAsset(candidate, '');
    if (path && !path.includes('/')) path = `slides/${path}`;
    if (/^thumbs\//i.test(path)) path = `slides/${path.slice(7)}`;
    return path;
}

function toThumb(thumb, slide) {
    if (thumb) {
        let path = cleanAsset(thumb, '');
        if (path && !path.includes('/')) path = `thumbs/${path}`;
        if (/^slides\//i.test(path)) path = `thumbs/${path.slice(7)}`;
        if (path) return path;
    }
    return thumbFromSlide(slide);
}

function thumbFromSlide(slide) {
    if (/^slides\//i.test(slide || '')) return `thumbs/${slide.slice(7)}`;
    return slide || '';
}

